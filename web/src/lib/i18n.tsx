const DICTS: Record<Lang, Partial<Dict>> = { en, hi, pa };
export const LANGS: { id: Lang; short: string; name: string }[] = [
  { id: "en", short: "EN", name: "English" },
  { id: "hi", short: "हिं", name: "हिन्दी" },
  { id: "pa", short: "ਪੰ", name: "ਪੰਜਾਬੀ" },
];

export type TFn = (key: DictKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// language store (localStorage-backed)
const LS_KEY = "dhuaan.lang";
const langSubs = new Set<() => void>();
function readLang(): Lang {
  if (typeof window === "undefined") return "en";
  // ?lang=hi|pa|en deep link wins (shareable notices, demo recordings)
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q === "en" || q === "hi" || q === "pa") return q;
  const v = window.localStorage.getItem(LS_KEY);
  return v === "hi" || v === "pa" ? v : "en";
}
let currentLang: Lang | null = null;
function getLang(): Lang {
  if (currentLang === null) currentLang = readLang();
  return currentLang;
}
export function setLang(l: Lang) {
  currentLang = l;
  try {
    window.localStorage.setItem(LS_KEY, l);
  } catch {}
  langSubs.forEach((s) => s());
}

interface I18n {
  lang: Lang;
  t: TFn;
  setLang: (l: Lang) => void;
  naqi: (c: NaqiCategory) => string;
  kind: (k: PlaceKind) => string;
}
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const lang = useSyncExternalStore(
    (cb) => {
      langSubs.add(cb);
      return () => langSubs.delete(cb);
    },
    getLang,
    () => "en" as Lang,
  );
  useEffect(() => {
    document.documentElement.lang = lang === "en" ? "en-IN" : lang === "hi" ? "hi" : "pa";
  }, [lang]);
  const t = useCallback<TFn>((key, vars) => translate(lang, key, vars), [lang]);
  const value = useMemo<I18n>(
    () => ({
      lang,
      t,
      setLang,
      naqi: (c) => translate(lang, `naqi.${c}` as DictKey),
      kind: (k) => translate(lang, `kind.${k}` as DictKey),
    }),
    [lang, t],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
